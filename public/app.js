  // Inline validation under each field; focus goes to the first problem.
  function validateAdd(f) {
    let first = null;
    Object.entries(REQUIRED).forEach(([name, msg]) => { const el = setFieldError(name, f[name] ? '' : msg); if (!f[name] && !first) first = el; });
    const bad = f.Followers && L.parseFollowers(f.Followers) === null;
    const fEl = setFieldError('Followers', bad ? 'Use digits, or a short form like 4.2k.' : '');
    if (bad && !first) first = fEl;
    if (first) first.focus();
    return !first;
  }

