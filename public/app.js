  const normalizeIg = (v) => {
    v = (v || '').trim();
    if (!v) return '';
    if (/^https?:\/\//i.test(v)) return v;
    if (/instagram\.com/i.test(v)) return `https://${v.replace(/^\/+/, '')}`;
    return `https://instagram.com/${v.replace(/^@/, '')}`;
  };
  const normalizeFb = (v) => {
    v = (v || '').trim();
    if (!v) return '';
    if (/^https?:\/\//i.test(v)) return v;
    if (/facebook\.com|fb\.com/i.test(v)) return `https://${v.replace(/^\/+/, '')}`;
    return `https://facebook.com/${v.replace(/^@/, '')}`;
  };

